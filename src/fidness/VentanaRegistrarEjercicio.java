    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        
        Categoria categoria = null;

        int posicion = cmbCategoria.getSelectedIndex();

        if (posicion > 0) {
            categoria = gimnasio.getCategorias().get(posicion - 1);
        }

        Ejercicio ejercicio = new Ejercicio(
                txtNombre.getText().trim(),
                txtDescripcion.getText().trim(),
                txtInstrucciones.getText().trim(),
                categoria
        );

        try {
            gimnasio.registrarEjercicio(ejercicio);

            JOptionPane.showMessageDialog(
                    this,
                    "Ejercicio registrado correctamente."
            );

            txtNombre.setText("");
            txtDescripcion.setText("");
            txtInstrucciones.setText("");
            cmbCategoria.setSelectedIndex(0);

        } catch (DatosInvalidosException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
        
    }//GEN-LAST:event_btnGuardarActionPerformed

