    public VentanaConsultarEjercicio(Gimnasio gimnasio) {
        initComponents();
        this.gimnasio = gimnasio;

        cmbCategoria.removeAllItems();
        cmbCategoria.addItem("Todas");

        for (Categoria categoria : gimnasio.getCategorias()) {
            cmbCategoria.addItem(categoria.getNombre());
        }

        cargando = false;
        cargarEjercicios();
    }
    
    private void cargarEjercicios() {

        int posicion = cmbCategoria.getSelectedIndex();

        if (posicion <= 0) {
            ejerciciosMostrados = gimnasio.consultarEjercicios();

        } else {
            Categoria categoria = gimnasio.getCategorias().get(posicion - 1);

            ejerciciosMostrados = gimnasio.consultarPorCategoria(categoria);
        }

        cmbEjercicio.removeAllItems();

        for (Ejercicio ejercicio : ejerciciosMostrados) {
            cmbEjercicio.addItem(ejercicio.getNombre()+ " - " + ejercicio.getCategoria().getNombre());
        }

        cmbEjercicio.setSelectedIndex(-1);

        if (ejerciciosMostrados.isEmpty()) {
            JOptionPane.showMessageDialog(this,"No hay ejercicios para mostrar.");
        }
    }

